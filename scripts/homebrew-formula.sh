#!/bin/sh
# Prints the Homebrew formula for a costgate release.
# Usage: scripts/homebrew-formula.sh <version without v> <path to checksums.txt>
# Used by .github/workflows/release.yml and for a manual tap update.
set -eu

version="${1:?version}"
checksums="${2:?checksums.txt}"

case "$version" in
  [0-9]*.[0-9]*.[0-9]*) ;;
  *) echo "invalid version: $version" >&2; exit 1 ;;
esac

sum() {
  s="$(awk -v f="costgate_${version}_$1.tar.gz" '$2 == f { print $1 }' "$checksums")"
  case "$s" in
    [0-9a-f]*) [ "${#s}" -eq 64 ] || { echo "bad sha256 for $1" >&2; exit 1; } ;;
    *) echo "no sha256 for $1 in $checksums" >&2; exit 1 ;;
  esac
  printf '%s' "$s"
}

# Resolve every checksum first: a failure inside $(...) in the heredoc
# would not stop the script.
darwin_arm64="$(sum darwin_arm64)"
darwin_amd64="$(sum darwin_amd64)"
linux_arm64="$(sum linux_arm64)"
linux_amd64="$(sum linux_amd64)"

base="https://github.com/leosavio/costgate/releases/download/v${version}"

cat <<EOF
# typed: false
# frozen_string_literal: true

# Generated by scripts/homebrew-formula.sh in leosavio/costgate. Do not edit by hand.
class Costgate < Formula
  desc "Offline, fail-closed monthly AWS cost projection of terraform/tofu plans"
  homepage "https://github.com/leosavio/costgate"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/costgate_${version}_darwin_arm64.tar.gz"
      sha256 "${darwin_arm64}"
    end
    on_intel do
      url "${base}/costgate_${version}_darwin_amd64.tar.gz"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/costgate_${version}_linux_arm64.tar.gz"
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "${base}/costgate_${version}_linux_amd64.tar.gz"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install "costgate"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/costgate version")
    assert_match "ok us-east-1", shell_output("#{bin}/costgate pricing verify")
  end
end
EOF
